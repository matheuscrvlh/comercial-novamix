WITH ULTIMA_DATA AS (
    SELECT IDEMPRESA, MAX(DTMOVIMENTO) AS DTMOVIMENTO
    FROM DBA.ESTOQUE_SALDO_ATUAL
    WHERE IDEMPRESA IN ({{FILIAIS}})
        AND DTMOVIMENTO <= CURRENT DATE
    GROUP BY IDEMPRESA
)
SELECT
    ES.IDEMPRESA,
    EM.NOMEFANTASIA AS NOME_EMPRESA,
    PV.IDSUBPRODUTO,
    PV.DESCRICAOPRODUTO,
    PV.IDCODBARPROD,
    CAST(ES.QTDATUALESTOQUE AS NUMERIC(15, 2)) AS QTDATUALESTOQUE,
    CAST(ES.VALATUALESTOQUE AS NUMERIC(15, 2)) AS VALATUALESTOQUE
FROM
    DBA.ESTOQUE_SALDO_ATUAL ES
    INNER JOIN ULTIMA_DATA UD ON UD.IDEMPRESA = ES.IDEMPRESA AND UD.DTMOVIMENTO = ES.DTMOVIMENTO
    INNER JOIN DBA.PRODUTOS_VIEW PV ON PV.IDSUBPRODUTO = ES.IDSUBPRODUTO
    INNER JOIN DBA.EMPRESA EM ON EM.IDEMPRESA = ES.IDEMPRESA
WHERE
    ES.IDEMPRESA IN ({{FILIAIS}})
    AND ES.QTDATUALESTOQUE < 0
ORDER BY
    ES.QTDATUALESTOQUE ASC
FETCH FIRST 50 ROWS ONLY;
